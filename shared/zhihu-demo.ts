import { z } from 'zod';

export const demoPreferencesSchema = z
  .object({
    recordHistory: z.boolean().default(true),
    emailNotifications: z.boolean().default(false),
    compactFeed: z.boolean().default(false),
  })
  .strict();
export const demoProfileInputSchema = z
  .object({
    displayName: z.string().trim().min(1).max(60),
    bio: z.string().trim().max(160),
    preferences: demoPreferencesSchema,
  })
  .strict();
export const demoActivityKindSchema = z.enum([
  'bookmark',
  'history',
  'vote',
  'follow',
]);
export type DemoActivityKind = z.infer<typeof demoActivityKindSchema>;
export type DemoPreferences = z.infer<typeof demoPreferencesSchema>;
export type DemoProfileInput = z.infer<typeof demoProfileInputSchema>;
export interface DemoArticle {
  id: string;
  title: string;
  author: string;
  bio: string;
  tags: string[];
  excerpt: string;
  paragraphs: string[];
  votes: number;
  comments: number;
  followers: number;
  views: number;
  color: string;
}
export interface DemoActivity {
  kind: DemoActivityKind;
  targetId: string;
  updatedAt: string;
}
export interface DemoAccount extends DemoProfileInput {
  userId: string;
  activity: DemoActivity[];
}

